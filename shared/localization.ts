export type Message = keyof typeof english;

export function translate(language: Language, message: Message, values: readonly unknown[] = []): string {
  const text = language === "en" ? english[message] : message;
  return text.replace(/\{(\d+)\}/g, (placeholder, index) =>
    Number(index) < values.length ? String(values[Number(index)]) : placeholder);
}
