const { app, BrowserWindow } = require('electron');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const assert = require('node:assert/strict');
const scratch = fs.mkdtempSync(path.join(os.tmpdir(), 'openfruit-xcode-smoke-'));
const root = path.join(scratch, 'NativeProject'), project = path.join(root, 'Demo.xcodeproj'), file = path.join(project, 'project.pbxproj');
fs.mkdirSync(project, { recursive: true });
fs.writeFileSync(file, require('./fixtures/xcode.cjs'));
fs.writeFileSync(path.join(root, 'Source.swift'), 'let value = 1\n');
app.setPath('userData', scratch);
process.env.OPENFRUIT_USER_STATE = path.join(scratch, 'engine-state');
fs.writeFileSync(path.join(scratch, 'session_state.json'), JSON.stringify({ currentScreen: 'ide', project: { name: 'NativeProject', projectPath: root }, tabs: [], activeTabId: null }));
require('../dist-electron/main.cjs');
const timeout = setTimeout(() => { console.error('Xcode smoke timeout'); app.exit(1); }, 30000);
app.whenReady().then(async () => {
  try {
    const win = BrowserWindow.getAllWindows()[0]; win.webContents.setBackgroundThrottling(false);
    const errors = [];
    win.webContents.on('console-message', ({ level, message }) => { if (level === 'error' && message.includes('Uncaught')) errors.push(message); });
    if (win.webContents.isLoading()) await new Promise(resolve => win.webContents.once('did-finish-load', resolve));
    const run = code => win.webContents.executeJavaScript(code);
    const wait = async predicate => {
      const deadline = Date.now() + 6000;
      while (Date.now() < deadline) { if (await predicate()) return; await new Promise(resolve => setTimeout(resolve, 30)); }
      throw new Error('Xcode UI state timeout: ' + await run('document.body.innerText.slice(-1800)'));
    };
    const click = text => run(`(() => { const button = [...document.querySelectorAll('[aria-label="Editor progetto Xcode"] button')].find(b => b.textContent.trim() === ${JSON.stringify(text)}); if (!button || button.disabled) throw new Error('Button unavailable: ' + ${JSON.stringify(text)}); button.click(); return true; })()`);
    const input = (label, value) => run(`(() => { const element = document.querySelector(${JSON.stringify('input[aria-label="' + label + '"]')}); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(element, ${JSON.stringify(value)}); element.dispatchEvent(new Event('input', { bubbles: true })); return true; })()`);
    const config = id => run(`(() => { const select = document.querySelector('select[aria-label="Configurazione Xcode"]'); select.value = ${JSON.stringify(id)}; select.dispatchEvent(new Event('change', { bubbles: true })); return true; })()`);
    await wait(() => run(`[...document.querySelectorAll('[data-file-path]')].some(node => node.getAttribute('data-file-path') === ${JSON.stringify(project)})`));
    assert.equal(await run(`[...document.querySelectorAll('[data-file-path]')].some(node => node.getAttribute('data-file-path') === ${JSON.stringify(file)})`), false);
    await run(`([...document.querySelectorAll('[data-file-path]')].find(node => node.getAttribute('data-file-path') === ${JSON.stringify(project)})).click(); true`);
    await wait(() => run(`document.querySelector('input[aria-label="Bundle ID"]')?.value === 'com.example.demo.debug'`));
    await config('APP_RELEASE');
    await wait(() => run(`document.querySelector('input[aria-label="Bundle ID"]')?.value === 'com.example.demo'`));
    await input('Bundle ID', 'com.changed.release');
    await click('Signing');
    await wait(() => run(`document.querySelector('input[aria-label="Development Team"]')?.placeholder.includes('PROJECT001')`));
    await input('Development Team', 'NEWTEAM001');
    await click('Widget'); await click('General');
    await wait(() => run(`document.querySelector('input[aria-label="Bundle ID"]')?.value === 'com.example.demo.widget'`));
    await run("document.querySelector('[data-xcode-target=APP]').click(); true"); await config('APP_RELEASE');
    await wait(() => run(`document.querySelector('input[aria-label="Bundle ID"]')?.value === 'com.changed.release'`));
    await click('Salva progetto');
    await wait(() => run(`document.querySelector('[aria-label=\"Editor progetto Xcode\"] [role=status]')?.textContent === 'Progetto salvato'`));
    const saved = await run(`window.openfruitApi.readXcodeProject(${JSON.stringify(project)})`);
    assert.equal(saved.targets[0].configurations[1].settings.PRODUCT_BUNDLE_IDENTIFIER, 'com.changed.release');
    assert.equal(saved.targets[0].configurations[1].settings.DEVELOPMENT_TEAM, 'NEWTEAM001');
    assert.equal(saved.targets[0].configurations[0].settings.PRODUCT_BUNDLE_IDENTIFIER, 'com.example.demo.debug');
    assert.equal(saved.targets[1].configurations[0].settings.PRODUCT_BUNDLE_IDENTIFIER, 'com.example.demo.widget');
    assert.equal(fs.existsSync(path.join(root, '.openfruit-studio.json')), false, 'Native settings must be saved in the pbxproj');
    await click('Dependencies');
    await wait(() => run(`document.querySelector('[aria-label="Editor progetto Xcode"]').textContent.includes('Collections')`));
    assert.equal(await run(`!!document.querySelector('[aria-label="Editor progetto Xcode"] textarea')`), false, 'Dependencies must be parsed rather than a raw file editor');
    await click('Build Phases');
    await wait(() => run(`document.querySelector('[aria-label="Editor progetto Xcode"]').textContent.includes('Source.swift')`));
    await click('General');
    await wait(() => run(`document.querySelector('input[aria-label="Bundle ID"]')?.value === 'com.changed.release'`));
    await run('new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))');
    await new Promise(resolve => setTimeout(resolve, 100));
    fs.writeFileSync(path.join(scratch, 'xcode-project-editor.png'), (await win.webContents.capturePage()).toPNG());
    await input('Bundle ID', 'com.local.unsaved');
    const external = fs.readFileSync(file, 'utf8') + '// external change\n'; fs.writeFileSync(file, external);
    await click('Salva progetto');
    await wait(() => run(`document.querySelector('[role=alert]')?.textContent.includes('modificato sul disco')`));
    assert.equal(fs.readFileSync(file, 'utf8'), external);
    assert.equal(await run(`document.querySelector('input[aria-label="Bundle ID"]').value`), 'com.local.unsaved');
    await run('window.confirm = () => true; true');
    await click('Ricarica progetto');
    await wait(() => run("document.querySelector('input[aria-label=\"Bundle ID\"]')?.value === 'com.example.demo.debug'"));
    assert.deepEqual(errors, []);
    console.log('PASS: Xcode package navigator, parsed project/targets/configurations, real bundle/team persistence, dependencies/phases and external-edit protection');
    clearTimeout(timeout); app.quit();
  } catch (error) { console.error(error); clearTimeout(timeout); app.exit(1); }
});
app.on('quit', () => { try { fs.rmSync(scratch, { recursive: true, force: true }); } catch {} });
